-- PEN-5885: persist WHETHER the gate was satisfied, so a served ask and a dead
-- one stop being the same record.
--
-- `approval-gate-reconciler.ts` already computes `disposition.satisfied`. It used
-- that boolean to pick one of four English sentences and then wrote
-- `status: 'cancelled'` on BOTH branches. So "the board merged the pull request
-- this card asked about" and "the pull request was closed unmerged and the ask
-- died" are indistinguishable in the row, and the board-decision gauge --
-- which excludes `cancelled` for the correct reason, that a requester retiring
-- its own moot card is not the board deciding anything -- could not tell them
-- apart and excluded both.
--
-- Measured on company b1d3f3d3 before this migration: 20 agent cards were
-- satisfied and retired by a fired gate inside a 72h window that
-- `paperclip_approval_last_decision_timestamp_seconds` reported as having no
-- board activity at all, and which paged Platform for 11 days on that reading.
-- A second, disjoint 60h window gave 7 more, against 0 uses of the decide verb.
-- The failure direction matters: the gauge UNDER-reports service, so it accuses
-- a board that is working, and it gets worse as `payload.gate` adoption spreads,
-- because every adoption moves one more ask out of the population that can
-- advance the gauge. Alert health and correct agent behaviour were anti-correlated.
ALTER TABLE "approvals" ADD COLUMN IF NOT EXISTS "gate_satisfied" boolean;

